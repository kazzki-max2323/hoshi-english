/* 場面ごとの 効果音。キラキラ（高い ベルの 音）を へらして、木琴・木の 音・紙の 音・声っぽい 音などに 分けた。
   beach/scene.js の tone / noise を つかう（scene.js は 手で 書きかえない ので、ここで BEACH.sfx に 足す）。
   どれも 小さめの 音で、毎回 すこし ちがう 高さに なる。 */
(()=>{const X=BEACH.sfx,P=a=>a[Math.random()*a.length|0],R=(a,b)=>a+Math.random()*(b-a);
/* 木琴（マリンバ）：まるくて あたたかい 音 */
const mar=(f,v=.05,dl=0,d=.32)=>{tone(f,d,'sine',v,dl);tone(f*4,d*.16,'sine',v*.16,dl);noise(.012,{v:v*.25,f:f*3,q:3,delay:dl})};
/* 木の ブロック：コトッ */
const wood=(f,v=.05,dl=0)=>{tone(f,.06,'sine',v,dl,f*.82);noise(.02,{v:v*.5,f:f*1.7,q:6,delay:dl})};
Object.assign(X,{
 /* ボタン・画面を ひらく（ふつう） */
 open:()=>{const f=P([392,440,494]);wood(f*2,.04);mar(f,.035,.04,.22)},
 /* 一歩 すすむ（つぎへ・えらぶ） */
 step:()=>wood(P([620,700,780]),.045),
 /* もどる・とじる：下がる 音 */
 back:()=>{const f=R(560,640);tone(f,.08,'sine',.035,0,f*.62)},
 /* 本・ノートを ひらく：紙を めくる 音 ＋ ぽすっ */
 book:()=>{noise(.14,{v:.06,f:2600,f2:900,q:.8,attack:.02});noise(.09,{v:.04,f:1800,f2:3400,q:.9,delay:.1,attack:.015});tone(150,.09,'sine',.06,.02,95)},
 /* お店：木の とびら カタン ＋ 木琴 2音 */
 shop:()=>{wood(330,.05);wood(250,.04,.07);const s=P([[392,523],[440,587],[349,466]]);mar(s[0],.035,.14);mar(s[1],.035,.24)},
 /* 授業へ：学校の チャイムを ひくい 木琴で */
 lesson:()=>{const s=P([[523,659,784],[392,494,587],[440,554,659]]);s.forEach((f,i)=>mar(f,.04,i*.1,.4))},
 /* ミナ先生・会話：声みたいな ぴょこっ */
 talk:()=>{const f=R(300,360);tone(f,.07,'sine',.06,0,f*1.5);tone(f*1.3,.08,'sine',.05,.08,f*1.9)},
 /* 図鑑・カード：カードを まぜる シャシャッ */
 card:()=>{for(let i=0;i<3;i++)noise(.04,{v:.05,f:R(2500,3800),q:1.2,delay:i*.05});tone(180,.06,'sine',.04,.15,140)},
 /* 宝の地図：紙を ひろげる ザーッ */
 map:()=>{noise(.45,{v:.05,type:'lowpass',f:500,f2:2200,attack:.12});wood(260,.04,.4)},
 /* 正解：木琴で ポロン（毎回 すこし ちがう） */
 correct:()=>{const s=P([[523,784],[587,880],[659,988],[523,659,784],[440,659]]);s.forEach((f,i)=>mar(f,.05,i*.075,.3))},
 /* まちがい：やさしい ぶぶっ */
 wrong:()=>{tone(233,.12,'triangle',.05,0,215);tone(196,.18,'triangle',.045,.12,180)},
 /* コインが 入る：小さい チャッ（キラキラ しない） */
 coinIn:()=>{tone(R(900,1200),.04,'triangle',.014);noise(.02,{v:.025,f:R(3000,4000),q:4})},
 /* かいもの：レジの カシャン ＋ 木琴 */
 buy:()=>{noise(.05,{v:.07,f:1800,q:2});tone(110,.08,'sine',.07,0,80);mar(P([523,587,659]),.04,.07);mar(P([784,880]),.035,.16)},
 /* 小さな クリア（授業・ふくしゅう・テストの おわり）：木琴の 上り ＋ ひくい 和音。ベルなし */
 done:()=>{const b=P([262,294,330]);[0,4,7,12].forEach((n,i)=>mar(b*2*Math.pow(2,n/12),.045,i*.09,.35));[0,7].forEach(n=>tone(b*Math.pow(2,n/12),.9,'triangle',.035,.38));wood(b*4,.03,.38)},
 /* だれかが 来た：コンコン */
 knock:()=>{wood(290,.07);wood(270,.06,.16)},
 /* お知らせ・おうえん：口笛みたいな ヒュイッ */
 hey:()=>{tone(620,.14,'sine',.04,0,900);tone(760,.2,'sine',.035,.17,1100)},
 /* ものを ひろう・ヒント：ポコン */
 pickup:()=>{tone(380,.08,'sine',.06,0,760);tone(700,.1,'sine',.045,.07,1050)},
 /* 文字を 1つ えらぶ：木の 音 */
 tap:()=>wood(P([700,800,900,1000]),.04)});
/* まだ 置きかえて いない ところで 鳴っても キラキラ しないように */
X.vopen=X.open})();
